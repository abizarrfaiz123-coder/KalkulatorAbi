    private void SamaDenganActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SamaDenganActionPerformed
        // TODO add your handling code here:
        switch(pilih) {
            case 1 : 
                bilangan2 = Double.parseDouble(String.valueOf(View.getText ()));
                jumlah = bilangan1 + bilangan2;
                bilangan = Double.toString(jumlah);
                break;
            case 2 : 
                bilangan2 = Double.parseDouble(String.valueOf(View.getText ()));
                jumlah = bilangan1 - bilangan2;
                bilangan = Double.toString(jumlah);
                break;
            case 3 : 
                bilangan2 = Double.parseDouble(String.valueOf(View.getText ()));
                jumlah = bilangan1 * bilangan2;
                bilangan = Double.toString(jumlah);
                break;
            case 4 : 
                bilangan2 = Double.parseDouble(String.valueOf(View.getText ()));
                jumlah = bilangan1 / bilangan2;
                bilangan = Double.toString(jumlah);
                break;  
        }
        
        if (jumlah % 1== 0) {
             View.setText(String.valueOf((int) jumlah));
        } else {
             View.setText(String.valueOf(jumlah));
        }         
    }//GEN-LAST:event_SamaDenganActionPerformed

